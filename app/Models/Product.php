<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\SoftDeletes;

class Product extends Model
{
    use HasFactory, SoftDeletes;

    protected $table = 'products';
    protected $guarded = [];

    protected $casts = [
        'is_featured' => 'boolean',
        'track_quantity' => 'boolean',
        'continue_selling_out_of_stock' => 'boolean',
        'requires_shipping' => 'boolean',
        'cost_price' => 'decimal:2',
        'low_stock_threshold' => 'integer',
        'sort_order' => 'integer',
    ];

    public function category()
    {
        return $this->belongsTo(Category::class);
    }

    public function variants()
    {
        return $this->hasMany(ProductVariant::class);
    }

    public function productImages()
    {
        return $this->hasManyThrough(ProductImage::class, ProductVariant::class, 'product_id', 'product_variant_id')
            ->orderByDesc('is_primary')
            ->orderBy('sort_order');
    }

    public function directImages()
    {
        return $this->hasMany(ProductImage::class, 'product_id')
            ->orderByDesc('is_primary')
            ->orderBy('sort_order');
    }

    public function prices()
    {
        return $this->hasManyThrough(ProductPrice::class, ProductVariant::class, 'product_id', 'product_variant_id');
    }

    public function coupons()
    {
        return $this->belongsToMany(Coupon::class, 'coupon_products', 'product_id', 'coupon_id');
    }

    public function orderItems()
    {
        return $this->hasManyThrough(OrderItem::class, ProductVariant::class, 'product_id', 'product_variant_id');
    }

    public function auditLogs()
    {
        return $this->hasMany(AuditLog::class, 'auditable_id')
            ->where('auditable_type', self::class)
            ->latest('id');
    }

    public function primaryVariant()
    {
        return $this->hasOne(ProductVariant::class)->oldestOfMany();
    }

    /**
     * Get primary image URL or fallback placeholder
     */
    public function getPrimaryImageUrlAttribute(): ?string
    {
        $image = $this->productImages->firstWhere('is_primary', true) 
            ?? $this->directImages->firstWhere('is_primary', true)
            ?? $this->productImages->first() 
            ?? $this->directImages->first();

        return $image?->media?->url;
    }

    /**
     * Active selling price helper
     */
    public function getSellingPriceAttribute(): float
    {
        $variant = $this->variants->first();
        $price = $variant?->currentPrice ?? $variant?->prices->first();
        return (float) ($price?->selling_price ?? 0);
    }

    /**
     * MRP helper
     */
    public function getMrpAttribute(): float
    {
        $variant = $this->variants->first();
        $price = $variant?->currentPrice ?? $variant?->prices->first();
        return (float) ($price?->mrp ?? 0);
    }

    /**
     * Total stock on hand aggregated across all variants
     */
    public function getTotalStockAttribute(): int
    {
        return (int) $this->variants->sum(function ($variant) {
            return $variant->inventory->sum('quantity_on_hand');
        });
    }

    /**
     * Total units sold across paid orders
     */
    public function getUnitsSoldAttribute(): int
    {
        return (int) $this->orderItems()
            ->whereHas('order', fn ($q) => $q->where('payment_status', 'paid'))
            ->sum('quantity');
    }

    /**
     * Total revenue generated by this product across paid orders
     */
    public function getTotalRevenueAttribute(): float
    {
        return (float) $this->orderItems()
            ->whereHas('order', fn ($q) => $q->where('payment_status', 'paid'))
            ->sum('line_total');
    }
}
